string food = Console.ReadLine();
int foodRations = int.Parse(food);
Console.WriteLine("Ilość członków drużyny:");
string members = Console.ReadLine();
int teamMembers = int.Parse(members);
Console.WriteLine("Liczba dni wyprawy:");
string days = Console.ReadLine();
int adventureDays = int.Parse(days);
int rationsPerMember = foodRations / teamMembers;
int leftovers = foodRations % teamMembers;
double rationsPerDayComa = (double)foodRations / adventureDays;
double rationsPerDay = Math.Round(rationsPerDayComa, 2);
double avgRations = Math.Round(rationsPerDay / teamMembers, 2);
Console.WriteLine($"Każdy członek drużyny otrzyma {rationsPerMember} pełnych racji");
Console.WriteLine($"Po równym podziale pozostanie {leftovers} racji");
Console.WriteLine($"Na całą drużynę przypadnie dziennie {rationsPerDay} racji");
Console.WriteLine($"Średnio na jedną osobę przypadnie {avgRations} racji na dzień");